#!/usr/bin/env python3
"""Write tests/zex_data.pico: ZEXDOC and ZEXALL as DataSection bytes.
The .com files are Frank Cringle's exercisers (GPL v2), in tests/upstream."""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = ['; Generated by tools/embed_zex.py from tests/upstream/zexdoc.com and zexall.com.',
       '; ZEXDOC/ZEXALL: Copyright (C) 1994 Frank D. Cringle, GPL v2 (tests/upstream).',
       'DataSection']
for name in ('zexdoc', 'zexall'):
    data = open(os.path.join(ROOT, 'tests', 'upstream', name + '.com'), 'rb').read()
    out.append('%s:' % ('ZexDoc' if name == 'zexdoc' else 'ZexAll'))
    for i in range(0, len(data), 32):
        out.append('  Data.a ' + ','.join('$%02X' % b for b in data[i:i + 32]))
    out.append('%sEnd:' % ('ZexDoc' if name == 'zexdoc' else 'ZexAll'))
out.append('EndDataSection')
for ext in ('pico', 'pico2'):
    with open(os.path.join(ROOT, 'tests', 'zex_data.' + ext), 'w', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
print('ok', len(out))
