#!/usr/bin/env python3
"""Turn the SingleStepTests Z80 vectors (tests/upstream/sst/head, the first
16 KB of each of the 1604 opcode files, MIT licence) into DataSection batches
tests/sst_batchN.pico / .pico2 that tests/sst.picow runs on the board.

Per vector, little-endian:
  13 words initial pc sp af bc de hl af' bc' de' hl' ix iy wz
  i r im flags(iff1 | iff2<<1 | qlast<<3)
  nram, then nram x (addr word, initial byte, final byte)
  nports, then nports x (addr word, value, dir 1=in 2=out)
  13 words final, i r im flags(iff1 | iff2<<1), q, cycles
Usage: py -3 tools/embed_sst.py [per_opcode] [max_bytes_per_batch]
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEAD = os.path.join(ROOT, 'tests', 'upstream', 'sst', 'head')
PER = int(sys.argv[1]) if len(sys.argv) > 1 else 5
MAXB = int(sys.argv[2]) if len(sys.argv) > 2 else 190000

REGS = ['pc', 'sp', 'af', 'bc', 'de', 'hl', 'af_', 'bc_', 'de_', 'hl_', 'ix', 'iy', 'wz']


def load(path, k):
    s = open(path, encoding='utf-8').read()
    parts = s[1:].split(',{"name"')
    out = []
    for i, pt in enumerate(parts):
        t = pt if i == 0 else '{"name"' + pt
        try:
            out.append(json.loads(t))
        except ValueError:
            break
        if len(out) >= k:
            break
    return out


def word(st, r):
    if r == 'af':
        return (st['a'] << 8) | st['f']
    if r == 'bc':
        return (st['b'] << 8) | st['c']
    if r == 'de':
        return (st['d'] << 8) | st['e']
    if r == 'hl':
        return (st['h'] << 8) | st['l']
    return st[r]


def encode(v):
    i, f = v['initial'], v['final']
    b = bytearray()
    for r in REGS:
        b += word(i, r).to_bytes(2, 'little')
    qlast = 1 if (i['q'] == i['f'] and i['q'] != 0) else 0
    if i['q'] not in (0, i['f']):
        raise ValueError('q not 0 or F')
    b += bytes([i['i'], i['r'], i['im'], i['iff1'] | (i['iff2'] << 1) | (qlast << 3)])
    init = dict(i['ram'])
    fin = dict(f['ram'])
    addrs = sorted(set(init) | set(fin))
    b.append(len(addrs))
    for a in addrs:
        iv = init.get(a, 0)
        b += a.to_bytes(2, 'little') + bytes([iv, fin.get(a, iv)])
    ports = v.get('ports') or []
    b.append(len(ports))
    for a, val, d in ports:
        b += a.to_bytes(2, 'little') + bytes([val, 1 if d == 'r' else 2])
    for r in REGS:
        b += word(f, r).to_bytes(2, 'little')
    b += bytes([f['i'], f['r'], f['im'], f['iff1'] | (f['iff2'] << 1), f['q'], len(v['cycles'])])
    return bytes(b)


def main():
    names = sorted(os.listdir(HEAD))
    blobs = []
    skipped = 0
    for n in names:
        for v in load(os.path.join(HEAD, n), PER):
            try:
                blobs.append(encode(v))
            except ValueError:
                skipped += 1
    batches, cur = [], []
    size = 0
    for bl in blobs:
        if size + len(bl) > MAXB and cur:
            batches.append(cur)
            cur, size = [], 0
        cur.append(bl)
        size += len(bl)
    batches.append(cur)
    for k, bt in enumerate(batches):
        data = b''.join(bt)
        lines = ['; Generated by tools/embed_sst.py: SingleStepTests Z80 vectors (MIT),',
                 '; batch %d of %d, %d vectors, %d bytes.' % (k + 1, len(batches), len(bt), len(data)),
                 '#SST_BATCH_COUNT = %d' % len(bt),
                 'DataSection', 'SstVectors:']
        for j in range(0, len(data), 32):
            lines.append('  Data.a ' + ','.join('$%02X' % x for x in data[j:j + 32]))
        lines.append('SstVectorsEnd:')
        lines.append('EndDataSection')
        for ext in ('pico', 'pico2'):
            with open(os.path.join(ROOT, 'tests', 'sst_batch%d.%s' % (k + 1, ext)), 'w', newline='\n') as fh:
                fh.write('\n'.join(lines) + '\n')
    print('vectors %d (q not representable, skipped: %d), batches %d: %s' %
          (len(blobs), skipped, len(batches), [len(b) for b in batches]))


if __name__ == '__main__':
    main()
