#!/usr/bin/env python3
"""Make the board's own test programs run on the desktop core.

Writes desktop/gen/: the bodies of tests/sst_body.pico, api_body.pico,
zex_body.pico and bench_body.pico with their Main() removed and their hooks
renamed per suite (the desktop program has one Z80PortIn/Out that routes to
the suite in use), plus all 8,020 SingleStepTests vectors in one DataSection.
Every rewrite must match the expected number of times, or the tool stops.

    py -3 tools/gen_desktop_tests.py
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GEN = os.path.join(ROOT, 'desktop', 'gen')


def must(text, old, new, count=1):
    k = text.count(old)
    if k != count:
        raise SystemExit('rewrite expected %d match(es), found %d: %r' % (count, k, old[:70]))
    return text.replace(old, new)


def drop_main(text):
    a = text.index('\nProcedure Main()\n')
    b = text.index('\nEndProcedure\n', a) + len('\nEndProcedure\n')
    return text[:a + 1] + text[b:]


def rename_hooks(text, prefix, hooks):
    for h in hooks:
        new = prefix + h[3:]   # Z80PortIn -> SstPortIn
        k = len(re.findall(r'\b%s\(' % h, text))
        if k == 0:
            raise SystemExit('%s: no %s' % (prefix, h))
        text = re.sub(r'\b%s\(' % h, new + '(', text)
    return text


def common(text):
    # PureBasic has a Hex() of its own.
    return re.sub(r'\bHex\(', 'HexN(', text)


def body(name):
    return open(os.path.join(ROOT, 'tests', name), encoding='utf-8').read()


def main():
    os.makedirs(GEN, exist_ok=True)
    hdr = '; Generated by tools/gen_desktop_tests.py from tests/%s - do not edit.\n'

    s = body('sst_body.pico')
    s = drop_main(s)
    s = rename_hooks(s, 'Sst', ['Z80PortIn', 'Z80PortOut'])
    open(os.path.join(GEN, 'sst_body.pbi'), 'w', newline='\n').write(hdr % 'sst_body.pico' + common(s))

    s = body('api_body.pico')
    s = drop_main(s)
    s = rename_hooks(s, 'Ap', ['Z80PortIn', 'Z80PortOut', 'Z80MemRead', 'Z80MemWrite'])
    s = must(s, 'Procedure ApCheck(*name.i, ok.i)', 'Procedure ApCheck(name.s, ok.i)')
    s = must(s, 'Say(*name)', 'Say(name)')
    s = s.replace('ProcedureRAM', 'Procedure')
    open(os.path.join(GEN, 'api_body.pbi'), 'w', newline='\n').write(hdr % 'api_body.pico' + common(s))

    s = body('zex_body.pico')
    s = drop_main(s)
    s = rename_hooks(s, 'Zex', ['Z80PortIn', 'Z80PortOut'])
    open(os.path.join(GEN, 'zex_body.pbi'), 'w', newline='\n').write(hdr % 'zex_body.pico' + common(s))

    s = body('bench_body.pico')
    s = drop_main(s)
    s = rename_hooks(s, 'Bn', ['Z80PortIn', 'Z80PortOut', 'Z80MemRead', 'Z80MemWrite'])
    s = s.replace('ProcedureRAM', 'Procedure')
    s = must(s, 'Procedure BnRun(*name.i, *code.i, n.i)', 'Procedure BnRun(*name, *code, n.i)')
    s = must(s, 'Say(*name)', 'SayA(*name)', 2)
    s = must(s, 'While BnUsed < 10000000\n      BnUsed = BnUsed + Z80Run(10000000 - BnUsed)',
             'While BnUsed < #BN_TSTATES\n      BnUsed = BnUsed + Z80Run(#BN_TSTATES - BnUsed)')
    s = must(s, 'BnUsed = Z80Run(1000000)', 'BnUsed = Z80Run(#BN_INSNS)')
    s = must(s, 'Procedure BnLoad(*code.i, n.i)', 'Procedure BnLoad(*code, n.i)')
    open(os.path.join(GEN, 'bench_body.pbi'), 'w', newline='\n').write(hdr % 'bench_body.pico' + common(s))

    # All vectors in one batch, for the desktop only.
    out = os.path.join(GEN, 'sst_vectors.pbi')
    r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'embed_sst.py'), '5', '100000000', '--out', out],
                       capture_output=True, text=True)
    if r.returncode != 0:
        raise SystemExit(r.stdout + r.stderr)
    print(r.stdout.strip())
    print('wrote desktop/gen/*.pbi')


if __name__ == '__main__':
    main()
